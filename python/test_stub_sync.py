"""Contract: the shipped type stub python/packaging/_halo.pyi covers every public name of peclet.halo._halo.

The stub is generated by nanobind.stubgen (recipe in its header and in python/CMakeLists.txt, next to
the rule that stages it). A binding added without regenerating it fails here, and so does a name in
the stub that the module does not define.

Run: PYTHONPATH=<python build tree> python -m pytest -q python/test_stub_sync.py
"""
import ast
from pathlib import Path

# mpi4py first: it initializes MPI, which peclet.halo never does itself.
from mpi4py import MPI  # noqa: F401
from peclet.halo import _halo

STUB = Path(__file__).resolve().parent / "packaging" / "_halo.pyi"


def _public(name):
    return not name.startswith("_") or name == "__init__"


def _members(cls):
    return {f"{cls.name}.{m.name}" for m in cls.body
            if isinstance(m, ast.FunctionDef) and _public(m.name)}


def _stub_names():
    names = set()
    for node in ast.parse(STUB.read_text()).body:
        if isinstance(node, ast.ClassDef):
            names |= {node.name} | _members(node)
        elif isinstance(node, ast.FunctionDef):
            names.add(node.name)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def _runtime_names():
    names = set()
    for name in dir(_halo):
        if name.startswith("_"):
            continue
        names.add(name)
        obj = getattr(_halo, name)
        if isinstance(obj, type):
            # A class without a bound constructor would still have nanobind's refusing __init__,
            # which carries no signature and is not part of the API.
            names.update(f"{name}.{m}" for m, v in vars(obj).items()
                         if _public(m) and (m != "__init__" or hasattr(v, "__nb_signature__")))
    return names


def test_stub_covers_every_public_name():
    missing = sorted(_runtime_names() - _stub_names())
    assert not missing, (f"public names of peclet.halo._halo missing from {STUB.name}: {missing}; "
                         "regenerate the stub (recipe in its header)")


def test_stub_names_exist_at_runtime():
    extra = _stub_names() - _runtime_names()
    assert not extra, f"names in {STUB.name} that peclet.halo._halo does not define: {sorted(extra)}"
